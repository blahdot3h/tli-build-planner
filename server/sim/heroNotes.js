export const heroNote = (name) => NOTES[name] ?? null;
export const heroNoteNames = () => Object.keys(NOTES);

// Notes for the hero's picked traits: "Hero trait X: ..."
export function heroNotes(hero) {
  const names = Object.values(hero?.traits ?? {}).filter(Boolean);
  return names.map((name) => (NOTES[name] ? `Hero trait ${name}: ${NOTES[name]}` : null)).filter(Boolean);
}
